    CLOCK_OFFSET = "TIME_CLOCK_OFFSET"
    SESSION_CLOSED = "TIME_SESSION_CLOSED"
    INTENT_IN_FUTURE = "TIME_INTENT_IN_FUTURE"

    RISK_APPROVED = "RISK_APPROVED"
    RISK_INPUT_MISSING = "STATE_RISK_INPUT_MISSING"
