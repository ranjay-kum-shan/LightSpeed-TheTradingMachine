"""Canonical machine-readable reason codes shared across components."""

from enum import StrEnum


class ReasonFamily(StrEnum):
    """Recognized reason-code namespaces."""

    BROKER = "BROKER"
    CONTROL = "CONTROL"
    DATA = "DATA"
    EXPOSURE = "EXPOSURE"
    KILL = "KILL"
    LOSS = "LOSS"
    MODE = "MODE"
    ORDER = "ORDER"
    RECON = "RECON"
    REPORT = "REPORT"
    RISK = "RISK"
    SECURITY = "SECURITY"
    STATE = "STATE"
    TIME = "TIME"


